import * as vscode from 'vscode';
import assert from 'node:assert/strict';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';

export async function run() {
  const ext = vscode.extensions.getExtension('local-james-black.c-relation-explorer');
  assert.ok(ext, 'extension registered');
  const root = vscode.workspace.workspaceFolders![0].uri;
  const excludedUri = vscode.Uri.joinPath(root, 'Tools', 'Polyspace', 'generated.c');
  const excludedPatterns = ['**/Tools/Polyspace/**', '**/{generated,vendor}/**'];
  await vscode.workspace.fs.createDirectory(vscode.Uri.joinPath(root, 'Tools', 'Polyspace'));
  await vscode.workspace.fs.writeFile(excludedUri, Buffer.from('void excluded(void){check_fault(1);}'));
  await vscode.workspace.getConfiguration('cRelation').update('exclude', excludedPatterns, vscode.ConfigurationTarget.Workspace);
  const originalFetch = globalThis.fetch;
  let automaticReleaseChecks = 0;
  globalThis.fetch = async (input, init) => {
    if (String(input).includes('/repos/mrdylee/vscode_extension_relation_window/releases')) {
      automaticReleaseChecks++;
      return new Response('', { status: 404 });
    }
    return originalFetch(input, init);
  };
  const api = await ext.activate();
  assert.ok(api.workspace, 'workspace analysis service exported');
  let indexTimeout: ReturnType<typeof setTimeout>;
  try {
    await Promise.race([api.workspace.ready.then(() => api.workspace.whenIdle()), new Promise((_, reject) => { indexTimeout = setTimeout(() => reject(new Error('Initial indexing did not finish within 15 seconds')), 15000); })]);
  } finally { clearTimeout(indexTimeout!); }
  await api.workspace.whenIdle();
  globalThis.fetch = originalFetch;
  assert.equal(automaticReleaseChecks, 0, 'test-mode activation never checks GitHub automatically');
  assert.ok((await vscode.commands.getCommands()).includes('cRelation.checkForUpdates'));
  assert.ok((await vscode.commands.getCommands()).includes('cRelation.openSettings'), 'scope settings command registered');
  assert.ok((await vscode.commands.getCommands()).includes('cRelation.help'), 'offline help command registered');
  assert.equal(api.workspace.index.files.size, 93, 'all files indexed beyond the document cache limit');
  let openedByReindex = 0;
  const opening = vscode.workspace.onDidOpenTextDocument(() => openedByReindex++);
  try { await api.workspace.reindex(); } finally { opening.dispose(); }
  assert.equal(openedByReindex, 0, 'background indexing must not open VS Code documents');
  assert.equal(api.workspace.index.files.has(excludedUri.toString()), false, 'initial indexing excludes configured folders');
  const document = await vscode.workspace.openTextDocument(vscode.Uri.joinPath(root, 'control.c'));
  const editor = await vscode.window.showTextDocument(document);
  await vscode.commands.executeCommand('cRelation.open');
  const offset = document.getText().indexOf('check_fault(1)');
  editor.selection = new vscode.Selection(document.positionAt(offset), document.positionAt(offset));
  await new Promise(resolve => setTimeout(resolve, 500));
  const selected = { ...api.view.state };
  assert.ok(selected.graph, JSON.stringify({ status: api.workspace.status, failures: [...api.workspace.failures], files: [...api.workspace.index.files.keys()], selected }));
  assert.equal(selected.graph.root.name, 'check_fault', 'selected symbol is graph root');
  const groups = selected.graph.root.children;
  assert.ok(groups.some((g: any) => g.name === 'fault_handlers' && g.kind === 'variable'));
  const control = groups.find((g: any) => g.name === 'control_task');
  assert.equal(control.sites.length, 2);
  const before = editor.selection.active;
  await api.view.handleMessage({ type: 'preview', id: control.sites[1].id });
  assert.equal(api.view.state.context.location.start, control.sites[1].location.start);
  assert.ok(api.view.state.context.tokens.flat().some((token: any) => token.kind === 'function' && token.text === 'check_fault'));
  assert.ok(editor.selection.active.isEqual(before), 'preview preserves main editor');
  assert.equal(api.view.state.graph.root.name, 'check_fault');
  await api.view.handleMessage({ type: 'mode', value: 'callers' });
  assert.equal(api.view.state.graph.root.children.some((g: any) => g.name === 'fault_handlers'), false);
  await api.view.handleMessage({ type: 'depth', value: 2 });
  assert.ok(api.view.state.graph.root.children.find((g: any) => g.name === 'control_task').children.some((g: any) => g.name === 'main'));
  await api.view.handleMessage({ type: 'collapse', key: control.key });
  assert.equal(api.view.state.graph.root.children.find((g: any) => g.name === 'control_task').children.length, 0);
  await api.view.handleMessage({ type: 'expand', key: control.key });
  assert.ok(api.view.state.graph.root.children.find((g: any) => g.name === 'control_task').children.length);
  const chainUri = vscode.Uri.joinPath(root, 'click-expansion.c');
  await vscode.workspace.fs.writeFile(chainUri, Buffer.from('void launch(void){main();}'));
  await new Promise(resolve => setTimeout(resolve, 500));
  await api.workspace.whenIdle();
  for (const depth of [1, 2]) {
    await api.view.handleMessage({ type: 'depth', value: depth });
    await api.view.handleMessage({ type: 'collapse', key: control.key });
    await api.view.handleMessage({ type: 'selectNode', key: control.key });
    const clicked = api.view.state.graph.root.children.find((g: any) => g.name === 'control_task');
    const main = clicked.children.find((g: any) => g.name === 'main');
    assert.ok(main, 'click expands callers from selected node');
    assert.equal(main.children.some((g: any) => g.name === 'launch'), depth === 2, 'click uses toolbar depth from selected node');
    assert.equal(api.view.state.context.location.start, control.location.start, 'click still previews symbol');
    assert.equal(api.view.state.graph.root.name, 'check_fault', 'click preserves root');
    assert.ok(editor.selection.active.isEqual(before), 'click preserves main editor');
    const expandedGraph = JSON.stringify(api.view.state.graph);
    await api.view.handleMessage({ type: 'selectNode', key: control.key });
    assert.equal(JSON.stringify(api.view.state.graph), expandedGraph, 'repeated click does not collapse or grow indefinitely');
  }
  await vscode.workspace.fs.delete(chainUri);
  await new Promise(resolve => setTimeout(resolve, 500));
  await api.workspace.whenIdle();
  await api.view.handleMessage({ type: 'lock' });
  const other = document.getText().indexOf('background_task(void)');
  editor.selection = new vscode.Selection(document.positionAt(other), document.positionAt(other));
  await new Promise(resolve => setTimeout(resolve, 200));
  assert.equal(api.view.state.graph.root.name, 'check_fault', 'locked root preserved');
  editor.selection = new vscode.Selection(document.positionAt(offset), document.positionAt(offset));
  await api.view.handleMessage({ type: 'lock' });
  await api.view.handleMessage({ type: 'open', id: control.sites[1].id });
  await new Promise(resolve => setTimeout(resolve, 250));
  assert.equal(editor.document.offsetAt(editor.selection.start), control.sites[1].location.start);
  assert.equal(api.view.state.graph.root.name, 'check_fault', 'explicit open preserves root');
  await api.view.handleMessage({ type: 'preview', id: 'file:///invalid@0' });
  assert.equal(api.view.state.graph.root.name, 'check_fault', 'unknown message targets ignored');
  const disabledOn = api.workspace.index.relations(selected.graph.root.symbolId, 'callers').find((g: any) => g.name === 'background_task').sites.length;
  assert.equal(disabledOn, 1);
  await vscode.workspace.getConfiguration('cRelation').update('skipInactive', false, vscode.ConfigurationTarget.Workspace);
  await new Promise(resolve => setTimeout(resolve, 200));
  await api.workspace.whenIdle();
  const disabledOff = api.workspace.index.relations(selected.graph.root.symbolId, 'callers').find((g: any) => g.name === 'background_task').sites.length;
  assert.equal(disabledOff, 2);
  await editor.edit(edit => edit.replace(new vscode.Range(document.positionAt(offset), document.positionAt(offset + 'check_fault(1)'.length)), 'check_fault(10)'));
  await new Promise(resolve => setTimeout(resolve, 300));
  await api.workspace.whenIdle();
  assert.ok(api.workspace.index.files.get(document.uri.toString()).text.includes('check_fault(10)'));
  const tempUri = vscode.Uri.joinPath(root, 'delete-me.c');
  await vscode.workspace.fs.writeFile(tempUri, Buffer.from('void extra(void){check_fault(1);}'));
  await new Promise(resolve => setTimeout(resolve, 500));
  await api.workspace.whenIdle();
  assert.ok(api.workspace.index.files.has(tempUri.toString()));
  await vscode.workspace.fs.delete(tempUri);
  await new Promise(resolve => setTimeout(resolve, 500));
  await api.workspace.whenIdle();
  assert.equal(api.workspace.index.files.has(tempUri.toString()), false);
  const ambiguousUris = ['port-a.h', 'port-b.h', 'use-port.c'].map(name => vscode.Uri.joinPath(root, name));
  for (const [i, uri] of ambiguousUris.entries()) await vscode.workspace.fs.writeFile(uri, Buffer.from(i < 2 ? '#define PORT_READY() 1\n' : 'void use_port(void) { PORT_READY(); }\n'));
  await new Promise(resolve => setTimeout(resolve, 500));
  await api.workspace.whenIdle();
  const ambiguousDocument = await vscode.workspace.openTextDocument(ambiguousUris[2]);
  const ambiguousEditor = await vscode.window.showTextDocument(ambiguousDocument);
  const ambiguousPosition = ambiguousDocument.positionAt(ambiguousDocument.getText().indexOf('PORT_READY'));
  ambiguousEditor.selection = new vscode.Selection(ambiguousPosition, ambiguousPosition);
  api.view.track(ambiguousEditor);
  assert.equal(api.view.state.candidates.length, 2);
  assert.equal(api.view.state.graph, undefined, 'ambiguous new symbol clears previous graph');
  assert.equal(api.view.state.context, undefined, 'ambiguous new symbol clears previous Context');
  api.view.refresh();
  assert.equal(api.view.state.graph, undefined, 'index refresh cannot restore stale graph');
  await api.view.handleMessage({ type: 'choose', id: api.view.state.candidates[0].id });
  assert.equal(api.view.state.graph.root.name, 'PORT_READY');
  assert.equal(api.view.state.candidates.length, 0);
  assert.ok(api.view.state.context.tokens.flat().some((token: any) => token.kind === 'preprocessor'));
  const variableUri = vscode.Uri.joinPath(root, 'variable-access.c');
  await vscode.workspace.fs.writeFile(variableUri, await readFile(path.resolve(__dirname, '../test/fixtures/variable-access.c')));
  await new Promise(resolve => setTimeout(resolve, 500));
  await api.workspace.whenIdle();
  const variableDocument = await vscode.workspace.openTextDocument(variableUri);
  const variableEditor = await vscode.window.showTextDocument(variableDocument);
  const variablePosition = variableDocument.positionAt(variableDocument.getText().indexOf('state'));
  variableEditor.selection = new vscode.Selection(variablePosition, variablePosition);
  api.view.track(variableEditor);
  assert.equal(api.view.state.graph.root.name, 'state');
  assert.equal(api.view.state.mode, 'callers', 'function preference persists for variable selection');
  assert.equal(api.view.state.graph.root.children.length, 4);
  await api.view.handleMessage({ type: 'access', value: 'write' });
  assert.deepEqual(api.view.state.graph.root.children.map((n: any) => n.name), ['updater', 'writer']);
  const writer = api.view.state.graph.root.children.find((n: any) => n.name === 'writer');
  assert.equal(writer.children[0].name, 'entry', 'variable uses continue into callers');
  await api.view.handleMessage({ type: 'preview', id: writer.sites[1].id });
  assert.equal(api.view.state.context.location.start, variableDocument.getText().indexOf('state = 2'));
  assert.ok(variableEditor.selection.active.isEqual(variablePosition));
  await api.view.handleMessage({ type: 'access', value: 'invalid' });
  assert.equal(api.view.state.accessFilter, 'write');
  await api.view.handleMessage({ type: 'access', value: 'address' });
  assert.deepEqual(api.view.state.graph.root.children.map((n: any) => n.name), ['escape']);
  assert.equal(api.view.state.context.location.start, variableDocument.getText().indexOf('state'), 'hidden selected site resets preview to root');
  // Keep all tracking regressions running so failures identify each lost-selection path.
  const trackingFailures: string[] = [];
  const expectRoot = (name: string, message: string) => {
    if (api.view.state.graph?.root.name !== name) trackingFailures.push(`${message}: expected ${name}, got ${api.view.state.graph?.root.name}`);
  };
  // A double-click selects the whole identifier, with the active cursor at its end.
  const writerOffset = variableDocument.getText().indexOf('writer(void)');
  variableEditor.selection = new vscode.Selection(variableDocument.positionAt(writerOffset), variableDocument.positionAt(writerOffset + 'writer'.length));
  await new Promise(resolve => setTimeout(resolve, 250));
  expectRoot('writer', 'unlocked tracking follows a selected identifier');
  variableEditor.selection = new vscode.Selection(variableDocument.positionAt(writerOffset + 2), variableDocument.positionAt(writerOffset + 2));
  api.view.track(variableEditor);
  const sameGraph = api.view.state.graph;
  api.view.track(variableEditor);
  if (api.view.state.graph !== sameGraph) trackingFailures.push('moving within the same symbol rebuilds its graph');
  const pendingFile = api.workspace.index.files.get(variableUri.toString());
  api.workspace.index.remove(variableUri.toString());
  const entryOffset = variableDocument.getText().indexOf('entry(void)');
  variableEditor.selection = new vscode.Selection(variableDocument.positionAt(entryOffset), variableDocument.positionAt(entryOffset));
  api.view.track(variableEditor); // Selection arrives while this file has no index entry.
  await new Promise(resolve => setTimeout(resolve, 200));
  api.workspace.index.update(pendingFile);
  api.workspace.changed.fire();
  await new Promise(resolve => setTimeout(resolve, 200));
  expectRoot('entry', 'selection during indexing is retried automatically');
  await api.view.handleMessage({ type: 'lock' });
  const switchedEditor = await vscode.window.showTextDocument(document);
  const switchedPosition = document.positionAt(document.getText().indexOf('background_task(void)'));
  switchedEditor.selection = new vscode.Selection(switchedPosition, switchedPosition);
  await new Promise(resolve => setTimeout(resolve, 200));
  await api.view.handleMessage({ type: 'lock' });
  expectRoot('background_task', 'unlock follows the most recently selected C editor');
  assert.deepEqual(trackingFailures, []);
  const contextPosition = document.positionAt(document.getText().indexOf('control_task(void)'));
  const contextClick = { type: 'navigateContext', uri: document.uri.toString(), line: contextPosition.line,
    column: contextPosition.character, text: document.lineAt(contextPosition.line).text };
  await api.view.handleMessage(contextClick);
  assert.equal(vscode.window.activeTextEditor?.document.uri.toString(), document.uri.toString());
  assert.ok(vscode.window.activeTextEditor?.selection.active.isEqual(contextPosition), 'Context click moves the main editor to the clicked token');
  assert.equal(api.view.state.graph?.root.name, 'control_task', 'Context click changes the unlocked Relation root');
  await api.view.handleMessage({ type: 'lock' });
  await api.view.handleMessage({ ...contextClick, line: switchedPosition.line, column: switchedPosition.character,
    text: document.lineAt(switchedPosition.line).text });
  assert.ok(vscode.window.activeTextEditor?.selection.active.isEqual(switchedPosition));
  assert.equal(api.view.state.graph?.root.name, 'control_task', 'locked Context navigation preserves the Relation root');
  for (const invalid of [{ ...contextClick, uri: 'file:///unrelated.c' }, { ...contextClick, line: -1 },
    { ...contextClick, column: 999999 }, { ...contextClick, text: 'outdated source' }]) await api.view.handleMessage(invalid);
  assert.ok(vscode.window.activeTextEditor?.selection.active.isEqual(switchedPosition), 'invalid and stale Context requests do not navigate');
  await api.view.handleMessage({ type: 'lock' });
  const callPosition = document.positionAt(document.getText().indexOf('check_fault(10)'));
  await api.view.handleMessage({ ...contextClick, line: callPosition.line, column: callPosition.character,
    text: document.lineAt(callPosition.line).text });
  assert.equal(api.view.state.graph?.root.name, 'check_fault');
  const faultDocument = await vscode.workspace.openTextDocument(vscode.Uri.joinPath(root, 'fault.c'));
  const countPosition = faultDocument.positionAt(faultDocument.getText().indexOf('fault_count'));
  await api.view.handleMessage({ type: 'navigateContext', uri: faultDocument.uri.toString(), line: countPosition.line,
    column: countPosition.character, text: faultDocument.lineAt(countPosition.line).text });
  assert.equal(vscode.window.activeTextEditor?.document.uri.toString(), faultDocument.uri.toString(), 'Context can navigate into a different file');
  assert.ok(vscode.window.activeTextEditor?.selection.active.isEqual(countPosition));
  assert.equal(api.view.state.graph?.root.name, 'fault_count', 'Context variable click switches to variable relations');
  const excludedDocument = await vscode.workspace.openTextDocument(excludedUri);
  if (process.platform === 'win32') {
    assert.equal(api.workspace.eligible(excludedUri.with({ path: excludedUri.path.toLowerCase() })), false, 'Windows exclusions ignore path casing');
    assert.equal(api.workspace.eligible(excludedUri.with({ path: excludedUri.path.toUpperCase() })), false, 'Windows drive and folder casing do not change exclusions');
  }
  const excludedEditor = await vscode.window.showTextDocument(excludedDocument);
  await excludedEditor.edit(edit => edit.insert(new vscode.Position(0, 0), '// unsaved excluded edit\n'));
  const generatedUri = vscode.Uri.joinPath(root, 'generated', 'late.c');
  await vscode.workspace.fs.createDirectory(vscode.Uri.joinPath(root, 'generated'));
  await vscode.workspace.fs.writeFile(generatedUri, Buffer.from('void excluded_late(void){}'));
  await new Promise(resolve => setTimeout(resolve, 500));
  await api.workspace.whenIdle();
  assert.equal(api.workspace.index.files.has(excludedUri.toString()), false, `editing excluded files does not add them: ${excludedUri} / ${excludedDocument.uri}`);
  assert.equal(api.workspace.index.files.has(excludedDocument.uri.toString()), false, 'normalized editor URI is also excluded');
  assert.equal(api.workspace.index.files.has(generatedUri.toString()), false, 'watchers honor glob exclusions');
  await vscode.workspace.getConfiguration('cRelation').update('exclude', [], vscode.ConfigurationTarget.Workspace);
  await new Promise(resolve => setTimeout(resolve, 500));
  await api.workspace.whenIdle();
  assert.ok(api.workspace.index.files.get(excludedUri.toString())?.text.includes('unsaved excluded edit'), 'removing exclusions reindexes unsaved buffers');
  assert.ok(api.workspace.index.files.has(generatedUri.toString()));
  await vscode.workspace.getConfiguration('cRelation').update('exclude', excludedPatterns, vscode.ConfigurationTarget.Workspace);
  await new Promise(resolve => setTimeout(resolve, 500));
  await api.workspace.whenIdle();
  assert.equal(api.workspace.index.files.has(excludedUri.toString()), false, 'adding exclusions removes old index entries');
  const settings = vscode.workspace.getConfiguration('cRelation');
  await settings.update('include', ['control.c', '*.h', 'Tools/**'], vscode.ConfigurationTarget.Workspace);
  await new Promise(resolve => setTimeout(resolve, 500));
  await api.workspace.whenIdle();
  assert.equal(api.workspace.index.files.has(faultDocument.uri.toString()), false, 'include removes files outside its patterns');
  assert.equal(api.workspace.index.files.has(document.uri.toString()), true, 'include retains matching files');
  assert.equal(api.workspace.index.files.has(excludedUri.toString()), false, 'exclude wins over include');
  await excludedEditor.edit(edit => edit.insert(new vscode.Position(0, 0), '// still excluded\n'));
  await settings.update('include', ['App/**', 'App/*.c', 'control.c'], vscode.ConfigurationTarget.Workspace);
  await new Promise(resolve => setTimeout(resolve, 500));
  await api.workspace.whenIdle();
  const appUri = vscode.Uri.joinPath(root, 'App', 'new.c');
  const outsideUri = vscode.Uri.joinPath(root, 'outside.c');
  await vscode.workspace.fs.createDirectory(vscode.Uri.joinPath(root, 'App'));
  await vscode.workspace.fs.writeFile(appUri, Buffer.from('void app_new(void){}'));
  await vscode.workspace.fs.writeFile(vscode.Uri.joinPath(root, 'App', 'notes.txt'), Buffer.from('not C source'));
  await vscode.workspace.fs.writeFile(outsideUri, Buffer.from('void outside(void){}'));
  const outsideEditor = await vscode.window.showTextDocument(faultDocument);
  await outsideEditor.edit(edit => edit.insert(new vscode.Position(0, 0), '// outside include\n'));
  await new Promise(resolve => setTimeout(resolve, 500));
  await api.workspace.whenIdle();
  assert.deepEqual([...api.workspace.index.files.keys()].sort(), [appUri.toString(), document.uri.toString()].sort(), 'watchers and edits honor include; non-C files stay out');
  await api.workspace.reindex();
  assert.equal(api.workspace.index.files.size, 2, 'overlapping include patterns do not duplicate files');
  const commaUri = vscode.Uri.joinPath(root, 'App,Main', 'comma.c');
  await vscode.workspace.fs.createDirectory(vscode.Uri.joinPath(root, 'App,Main'));
  await vscode.workspace.fs.writeFile(commaUri, Buffer.from('void comma_target(void){}'));
  for (const [patterns, expected] of [
    [['App/**/*.{c,h}', 'control.c', 'App/**'], [appUri.toString(), document.uri.toString()]],
    [['App,Main/**', 'control.c'], [commaUri.toString(), document.uri.toString()]]
  ]) {
    await settings.update('include', patterns, vscode.ConfigurationTarget.Workspace);
    await new Promise(resolve => setTimeout(resolve, 500));
    await api.workspace.whenIdle();
    await api.workspace.reindex();
    assert.deepEqual([...api.workspace.index.files.keys()].sort(), expected.sort(), 'independent include patterns preserve braces and literal commas');
    await vscode.workspace.fs.writeFile(appUri, Buffer.from('void app_edited(void){}'));
    await new Promise(resolve => setTimeout(resolve, 500));
    await api.workspace.whenIdle();
    const afterEdit = [...api.workspace.index.files.keys()].sort();
    await api.workspace.reindex();
    assert.deepEqual([...api.workspace.index.files.keys()].sort(), afterEdit, 'watcher and rebuild agree for complex include patterns');
  }
  await settings.update('include', ['no-such-folder/**'], vscode.ConfigurationTarget.Workspace);
  await new Promise(resolve => setTimeout(resolve, 500));
  await api.workspace.whenIdle();
  assert.equal(api.workspace.index.files.size, 0, 'no include matches means zero files, not fallback to all');
  await settings.update('include', [], vscode.ConfigurationTarget.Workspace);
  await new Promise(resolve => setTimeout(resolve, 500));
  await api.workspace.whenIdle();
  assert.ok(api.workspace.index.files.has(outsideUri.toString()), 'empty include restores the full scope');
  assert.ok(api.workspace.index.files.get(faultDocument.uri.toString()).text.includes('outside include'), 'restored scope uses unsaved content');
  assert.equal(api.workspace.index.files.has(excludedUri.toString()), false, 'empty include still respects exclude');
  const rootBeforeHelp = api.view.state.graph?.root.symbolId;
  const guideUri = vscode.Uri.joinPath(ext.extensionUri, 'USER_GUIDE.md');
  const guide = Buffer.from(await vscode.workspace.fs.readFile(guideUri)).toString('utf8');
  assert.ok(guide.includes('Exclude always wins.') && guide.includes('cRelation.include'), 'bundled guide explains scope precedence');
  await api.view.handleMessage({ type: 'help' });
  await new Promise(resolve => setTimeout(resolve, 500));
  assert.ok(vscode.window.tabGroups.all.flatMap(group => group.tabs).some(tab => tab.input instanceof vscode.TabInputWebview && /USER_GUIDE/.test(tab.label)), 'Help opens a rendered offline guide');
  assert.equal(api.view.state.graph?.root.symbolId, rootBeforeHelp, 'Help preserves Relation root');
  await api.view.handleMessage({ type: 'settings' });
  await new Promise(resolve => setTimeout(resolve, 300));
  assert.ok(vscode.window.tabGroups.all.flatMap(group => group.tabs).some(tab => tab.label === 'Settings'), 'Settings opens the native settings editor');
  assert.equal(api.view.state.graph?.root.symbolId, rootBeforeHelp, 'Settings preserves Relation root');
  const output = process.env.C_RELATION_TEST_OUTPUT!;
  await mkdir(path.dirname(output), { recursive: true });
  await writeFile(output, JSON.stringify({ passed: true, checks: ['Context source navigation and relation reroot', 'Context cross-file variable navigation', 'Context lock and stale-message checks', 'selected identifier tracking', 'selection retry after indexing', 'unlock follows latest editor', 'same-symbol graph reuse', 'variable selection and access filters', 'variable actual-site preview preserves editor', 'variable access filter validation', 'variable uses continue into caller tree', 'activation', '93-file index completion', 'indexing does not open documents', 'WASM worker', 'click tracking', 'variable icon data', 'call sites', 'Context preserves editor', 'mode/depth/expand/collapse', 'locked root', 'explicit source open', 'invalid message target', '#if0 setting reindex', 'unsaved buffer', 'file create/delete', 'ambiguous symbol clears stale graph and Context', 'candidate selection'] }, null, 2));
  console.log('C Relation extension integration checks passed');
}
