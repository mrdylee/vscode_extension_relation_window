import { test } from 'node:test';
import assert from 'node:assert/strict';
import { createAnalyzer } from '../src/analyzer';
import { RelationIndex } from '../src/relations';
import { CallbackOverrideStore, makeCallbackOverride } from '../src/callback-overrides';
test('user target survives reload and line shifts but needs review for code changes', async () => {
  const parser=await createAnalyzer('node_modules/web-tree-sitter/web-tree-sitter.wasm','node_modules/tree-sitter-c/tree-sitter-c.wasm');
  const source='typedef void(*CB)(void);void wrong(void){}static void correct(void){}CB cb=wrong;void run(void){cb();}';
  const index=new RelationIndex();index.update(parser.analyze('file:///manual.c',source));
  const site=index.files.get('file:///manual.c')!.references.find(ref=>ref.kind==='call')!;
  const symbols=index.symbols(),wrong=symbols.find(s=>s.name==='wrong')!,correct=symbols.find(s=>s.name==='correct')!;
  const record=makeCallbackOverride(index,site.location,wrong.id,correct.id);
  const store=new CallbackOverrideStore();store.set(record);
  assert.equal(store.resolve(index)[0].status,'active');
  const restored=new CallbackOverrideStore(JSON.parse(JSON.stringify(store.records())));
  index.update(parser.analyze('file:///manual.c','\n\n'+source));
  assert.equal(restored.resolve(index)[0].status,'active');
  assert.equal(restored.resolve(index)[0].target?.name,'correct');
  index.update(parser.analyze('file:///manual.c',source.replace('cb();','cb();cb();')));
  assert.equal(restored.resolve(index)[0].status,'needs-review');
  restored.remove(record.key);assert.equal(restored.records().length,0);
});
test('same names in different files remain distinct and missing target cannot be assigned', async () => {
  const parser=await createAnalyzer('node_modules/web-tree-sitter/web-tree-sitter.wasm','node_modules/tree-sitter-c/tree-sitter-c.wasm');
  const index=new RelationIndex();
  index.update(parser.analyze('file:///run.c','typedef void(*CB)(void);CB cb;void run(void){cb();}'));
  index.update(parser.analyze('file:///table.c','static void handler(void){}'));
  index.update(parser.analyze('file:///other.c','static void handler(void){}'));
  const site=index.files.get('file:///run.c')!.references.find(ref=>ref.kind==='call')!;
  const [a,b]=index.symbols().filter(s=>s.name==='handler');
  const record=makeCallbackOverride(index,site.location,a.id,b.id);
  const store=new CallbackOverrideStore();store.set(record);
  assert.equal(store.resolve(index)[0].target?.location.uri,'file:///other.c');
  assert.throws(()=>makeCallbackOverride(index,site.location,a.id,'missing'));
});
test('two call selections stay independent and registered static targets track dependency changes',async()=>{
  const parser=await createAnalyzer('node_modules/web-tree-sitter/web-tree-sitter.wasm','node_modules/tree-sitter-c/tree-sitter-c.wasm'),index=new RelationIndex();
  index.update(parser.analyze('file:///run.c','typedef void(*CB)(void);CB a,b;void run(void){a();b();}'));
  const table='typedef void(*CB)(void);static void wrong(void){}static void handler(void){}CB get(void){return handler;}';
  index.update(parser.analyze('file:///table.c',table));
  const wrong=index.symbols().find(s=>s.name==='wrong')!,handler=index.symbols().find(s=>s.name==='handler')!,sites=index.files.get('file:///run.c')!.references.filter(ref=>ref.kind==='call');
  const store=new CallbackOverrideStore();for(const site of sites)store.set(makeCallbackOverride(index,site.location,wrong.id,handler.id));
  assert.equal(store.records().length,2);assert.notEqual(store.records()[0].key,store.records()[1].key);
  assert.equal(store.revision(store.records()[0].key),1);
  index.update(parser.analyze('file:///table.c','/* moved */\n'+table));
  assert.ok(store.resolve(index).every(value=>value.status==='active'&&value.target?.storage==='static'));
  store.remove(store.records()[0].key);assert.equal(store.records().length,1);
  index.update(parser.analyze('file:///table.c',table.replace('handler(void){}','handler(void){int changed=1;}')));
  assert.equal(store.resolve(index)[0].status,'needs-review');
});
